package com.example.practical_training.model;

public class LevelConfig {
    private Integer levelId;
    private String title;
    private Integer width;
    private Integer height;
    private Integer spawnX;
    private Integer spawnY;
    private Integer goalX;
    private Integer goalY;

    public Integer getLevelId() {
        return levelId;
    }

    public void setLevelId(Integer levelId) {
        this.levelId = levelId;
    }

    public String getTitle() {
        return title;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public Integer getWidth() {
        return width;
    }

    public void setWidth(Integer width) {
        this.width = width;
    }

    public Integer getHeight() {
        return height;
    }

    public void setHeight(Integer height) {
        this.height = height;
    }

    public Integer getSpawnX() {
        return spawnX;
    }

    public void setSpawnX(Integer spawnX) {
        this.spawnX = spawnX;
    }

    public Integer getSpawnY() {
        return spawnY;
    }

    public void setSpawnY(Integer spawnY) {
        this.spawnY = spawnY;
    }

    public Integer getGoalX() {
        return goalX;
    }

    public void setGoalX(Integer goalX) {
        this.goalX = goalX;
    }

    public Integer getGoalY() {
        return goalY;
    }

    public void setGoalY(Integer goalY) {
        this.goalY = goalY;
    }
}

